import { randomUUID } from 'crypto'
import type { Database } from 'better-sqlite3'
import { addDays, minDate, toLocalDate } from '@shared/dates'
import type { Task, TaskCounts } from '@shared/ipc'
import type {
  NewTask,
  Recurrence,
  RemoveTask,
  RescheduleOverdue,
  RescheduleTask,
  TaskQuery,
  UpdateTask
} from '@shared/schemas'
import type { Clock } from '../clock'
import { createActivityRepo } from '../db/activity-repo'
import {
  createTasksRepo,
  toTask,
  type SeriesColumns,
  type TaskColumns,
  type TaskRow
} from '../db/tasks-repo'
import { AppError } from '../errors'
import { firstOccurrence, occurrencesBetween, weekdayMask } from '../recurrence'

/** How far ahead recurring tasks are generated by default. */
const DEFAULT_HORIZON_DAYS = 30
/** The furthest a date-range query can pull generation, e.g. paging through the calendar. */
const MAX_HORIZON_DAYS = 366

interface Deps {
  db: Database
  clock: Clock
  onChange?: (ids: string[]) => void
}

type Touch = (id: string) => void

export function createTaskService({ db, clock, onChange = () => {} }: Deps) {
  const repo = createTasksRepo(db)
  const activity = createActivityRepo(db)

  const today = (): string => toLocalDate(clock.now())
  const timestamp = (): string => clock.now().toISOString()

  /** Runs `work` in one transaction and announces what changed only once it has committed. */
  function mutate<T>(work: (touch: Touch, at: string) => T): T {
    const touched = new Set<string>()
    const result = db.transaction(() => work((id) => touched.add(id), timestamp()))()
    if (touched.size > 0) onChange([...touched])
    return result
  }

  function requireTask(id: string) {
    const row = repo.find(id)
    if (!row) throw new AppError('NOT_FOUND', 'That task no longer exists.')
    return row
  }

  function requireCategory(id: string | null | undefined): void {
    if (!id) return
    const found = db.prepare('SELECT 1 FROM categories WHERE id = ?').get(id)
    if (!found) throw new AppError('NOT_FOUND', 'That category no longer exists.')
  }

  function assertNotPast(date: string): void {
    if (date < today()) {
      throw new AppError('PAST_DATE', 'Tasks can only be scheduled for today or later.')
    }
  }

  function assertOpen(task: TaskRow): void {
    if (task.status === 'done') {
      throw new AppError('TASK_CLOSED', 'Reopen this task before changing its date.')
    }
  }

  function materialize(until: string): void {
    for (const series of repo.seriesBehind(until)) {
      const start = addDays(series.materialized_through, 1)
      for (const date of occurrencesBetween(series.weekdays, start, until)) {
        repo.insertOccurrence(series, randomUUID(), date, timestamp())
      }
      repo.patchSeries(series.id, { materialized_through: until })
    }
  }

  const defaultHorizon = (): string => addDays(today(), DEFAULT_HORIZON_DAYS)

  /**
   * The one place a task's date changes. Moving a scheduled task is a reschedule and is logged
   * as one; giving an unscheduled task its first date, or clearing a date, is an ordinary edit.
   */
  function applyDate(
    task: TaskRow,
    date: string | null,
    time: string | null | undefined,
    at: string,
    touch: Touch
  ): void {
    assertOpen(task)
    touch(task.id)
    const nextTime = time === undefined ? task.time : time

    if (date === null) {
      if (task.series_id) throw new AppError('DATE_REQUIRED', 'A repeating task needs a date.')
      repo.patch(task.id, {
        date: null,
        time: null,
        status: 'pending',
        reminded_at: null,
        updated_at: at
      })
      activity.add({
        taskId: task.id,
        taskTitle: task.title,
        action: 'edited',
        changes: { date: [task.date, null] },
        at
      })
      return
    }

    assertNotPast(date)

    if (task.date === null) {
      repo.patch(task.id, {
        date,
        time: nextTime,
        original_date: task.original_date ?? date,
        reminded_at: null,
        updated_at: at
      })
      activity.add({
        taskId: task.id,
        taskTitle: task.title,
        action: 'edited',
        changes: { date: [null, date] },
        at
      })
      return
    }

    repo.patch(task.id, {
      date,
      time: nextTime,
      status: 'rescheduled',
      reschedule_count: task.reschedule_count + 1,
      // A new date or time means a new reminder.
      reminded_at: null,
      updated_at: at
    })
    activity.add({
      taskId: task.id,
      taskTitle: task.title,
      action: 'rescheduled',
      fromDate: task.date,
      toDate: date,
      at
    })
  }

  function applyRecurrence(id: string, recurrence: Recurrence, at: string, touch: Touch): void {
    const task = requireTask(id)
    const series = task.series_id ? repo.findSeries(task.series_id) : undefined

    if (recurrence.kind === 'none') {
      const alreadyEnded = series?.end_date && task.occurrence_date! >= series.end_date
      if (!series || alreadyEnded) return
      repo.patchSeries(series.id, { end_date: task.occurrence_date, updated_at: at })
      repo
        .patchOpenOccurrences(series.id, addDays(task.occurrence_date!, 1), { deleted_at: at })
        .forEach(touch)
      logRecurrenceChange(task, series.recurrence, 'none', at)
      touch(id)
      return
    }

    const anchor = task.occurrence_date ?? task.date
    if (!anchor) throw new AppError('DATE_REQUIRED', 'A repeating task needs a date.')
    const weekdays = weekdayMask(recurrence, anchor)

    // An edit form sends the whole task back, so an unchanged value has to be a no-op even on a
    // finished occurrence.
    const unchanged =
      series?.recurrence === recurrence.kind && series.weekdays === weekdays && !series.end_date
    if (unchanged) return
    assertOpen(task)

    if (series) {
      repo.clearGeneratedOccurrences(series.id, anchor).forEach(touch)
      repo.patchSeries(series.id, {
        recurrence: recurrence.kind,
        weekdays,
        end_date: null,
        materialized_through: anchor,
        updated_at: at
      })
      logRecurrenceChange(task, series.recurrence, recurrence.kind, at)
    } else {
      const seriesId = randomUUID()
      repo.insertSeries({
        id: seriesId,
        title: task.title,
        notes: task.notes,
        time: task.time,
        priority: task.priority,
        category_id: task.category_id,
        recurrence: recurrence.kind,
        weekdays,
        start_date: anchor,
        end_date: null,
        materialized_through: anchor,
        created_at: at,
        updated_at: at
      })
      repo.patch(id, { series_id: seriesId, occurrence_date: anchor, updated_at: at })
      logRecurrenceChange(task, 'none', recurrence.kind, at)
    }
    touch(id)
    materialize(defaultHorizon())
  }

  function logRecurrenceChange(task: TaskRow, from: string, to: string, at: string): void {
    activity.add({
      taskId: task.id,
      taskTitle: task.title,
      action: 'edited',
      changes: { recurrence: [from, to] },
      at
    })
  }

  return {
    /** Tops up recurring occurrences. Safe to call any time, and called on launch. */
    ensureOccurrences(): void {
      db.transaction(() => materialize(defaultHorizon()))()
    },

    list(query: TaskQuery): Task[] {
      return db.transaction(() => {
        const furthest = addDays(today(), MAX_HORIZON_DAYS)
        materialize(query.to ? minDate(query.to, furthest) : defaultHorizon())
        return repo.list(query)
      })()
    },

    get(id: string): Task {
      return toTask(requireTask(id))
    },

    counts(): TaskCounts {
      return db.transaction(() => {
        materialize(defaultHorizon())
        return repo.counts(today())
      })()
    },

    create(input: NewTask): Task {
      return mutate((touch, at) => {
        const recurrence: Recurrence = input.recurrence ?? { kind: 'none' }
        const repeating = recurrence.kind === 'none' ? null : recurrence
        let date = input.date ?? (repeating ? today() : null)
        const time = input.time ?? null

        if (time && !date) throw new AppError('DATE_REQUIRED', 'Pick a date to set a time.')
        if (date) assertNotPast(date)
        requireCategory(input.categoryId)

        const fields = {
          title: input.title,
          notes: input.notes ?? '',
          time,
          priority: input.priority ?? 'medium',
          category_id: input.categoryId ?? null
        }

        let seriesId: string | null = null
        if (repeating) {
          const weekdays = weekdayMask(repeating, date!)
          date = firstOccurrence(weekdays, date!)
          seriesId = randomUUID()
          repo.insertSeries({
            ...fields,
            id: seriesId,
            recurrence: repeating.kind,
            weekdays,
            start_date: date,
            end_date: null,
            materialized_through: date,
            created_at: at,
            updated_at: at
          })
        }

        const id = randomUUID()
        repo.insert({
          ...fields,
          id,
          date,
          series_id: seriesId,
          occurrence_date: seriesId ? date : null,
          original_date: date,
          created_at: at,
          updated_at: at
        })
        activity.add({ taskId: id, taskTitle: input.title, action: 'created', toDate: date, at })
        touch(id)

        if (repeating) materialize(defaultHorizon())
        return toTask(requireTask(id))
      })
    },

    update({ id, patch, scope = 'this' }: UpdateTask): Task {
      return mutate((touch, at) => {
        const task = requireTask(id)
        if (scope === 'following') {
          if (!task.series_id) {
            throw new AppError('NOT_RECURRING', 'This task is not part of a repeating series.')
          }
          if (patch.date !== undefined) {
            throw new AppError('VALIDATION', 'Occurrences can only be moved one at a time.')
          }
        }
        requireCategory(patch.categoryId)

        const columns: TaskColumns = {}
        const changes: Record<string, [unknown, unknown]> = {}
        const edit = <K extends keyof TaskRow>(
          field: string,
          column: K,
          value: TaskRow[K] | undefined
        ): void => {
          if (value === undefined || value === task[column]) return
          columns[column as keyof TaskColumns] = value as never
          changes[field] = [task[column], value]
        }

        edit('title', 'title', patch.title)
        edit('notes', 'notes', patch.notes)
        edit('priority', 'priority', patch.priority)
        edit('categoryId', 'category_id', patch.categoryId)

        const moving = patch.date !== undefined && patch.date !== task.date
        if (moving) {
          applyDate(task, patch.date!, patch.time, at, touch)
        } else {
          if (patch.time && !task.date) {
            throw new AppError('DATE_REQUIRED', 'Pick a date to set a time.')
          }
          edit('time', 'time', patch.time)
        }

        if (Object.keys(columns).length > 0) {
          const rearm = columns.time !== undefined ? { reminded_at: null } : {}
          repo.patch(id, { ...columns, ...rearm, updated_at: at })
          activity.add({ taskId: id, taskTitle: task.title, action: 'edited', changes, at })
          touch(id)

          if (scope === 'following') {
            repo.patchSeries(task.series_id!, { ...columns, updated_at: at } as SeriesColumns)
            repo
              .patchOpenOccurrences(task.series_id!, task.occurrence_date!, {
                ...columns,
                updated_at: at
              })
              .forEach(touch)
          }
        }

        if (patch.recurrence) applyRecurrence(id, patch.recurrence, at, touch)
        return toTask(requireTask(id))
      })
    },

    complete(id: string): Task {
      return mutate((touch, at) => {
        const task = requireTask(id)
        // Two windows can tick the same task; the second click isn't a second completion.
        if (task.status === 'done') return toTask(task)
        repo.patch(id, { status: 'done', completed_at: at, updated_at: at })
        activity.add({ taskId: id, taskTitle: task.title, action: 'completed', at })
        touch(id)
        return toTask(requireTask(id))
      })
    },

    reopen(id: string): Task {
      return mutate((touch, at) => {
        const task = requireTask(id)
        if (task.status !== 'done') return toTask(task)

        const overdue = task.date !== null && task.date < today()
        repo.patch(id, {
          status: overdue ? 'missed' : task.reschedule_count > 0 ? 'rescheduled' : 'pending',
          completed_at: null,
          missed_at: overdue ? (task.missed_at ?? at) : task.missed_at,
          updated_at: at
        })
        activity.add({ taskId: id, taskTitle: task.title, action: 'reopened', at })
        touch(id)
        return toTask(requireTask(id))
      })
    },

    reschedule({ id, date, time }: RescheduleTask): Task {
      return mutate((touch, at) => {
        const task = requireTask(id)
        if (date !== task.date) {
          applyDate(task, date, time, at, touch)
        } else if (time !== undefined && time !== task.time) {
          // Same day, new time: an edit, not a reschedule.
          assertOpen(task)
          repo.patch(id, { time, reminded_at: null, updated_at: at })
          activity.add({
            taskId: id,
            taskTitle: task.title,
            action: 'edited',
            changes: { time: [task.time, time] },
            at
          })
          touch(id)
        }
        return toTask(requireTask(id))
      })
    },

    rescheduleOverdue({ date, ids }: RescheduleOverdue): Task[] {
      return mutate((touch, at) => {
        assertNotPast(date)
        const overdue = repo.overdue(today())
        const wanted = ids ? new Set(ids) : null
        const moved = overdue.filter((task) => !wanted || wanted.has(task.id))
        for (const task of moved) applyDate(task, date, undefined, at, touch)
        return moved.map((task) => toTask(requireTask(task.id)))
      })
    },

    remove({ id, scope = 'this' }: RemoveTask): void {
      mutate((touch, at) => {
        const task = requireTask(id)
        if (scope === 'following') {
          if (!task.series_id) {
            throw new AppError('NOT_RECURRING', 'This task is not part of a repeating series.')
          }
          repo.patchSeries(task.series_id, {
            end_date: addDays(task.occurrence_date!, -1),
            updated_at: at
          })
          repo
            .patchOpenOccurrences(task.series_id, task.occurrence_date!, {
              deleted_at: at,
              updated_at: at
            })
            .forEach(touch)
        }
        repo.patch(id, { deleted_at: at, updated_at: at })
        activity.add({ taskId: id, taskTitle: task.title, action: 'deleted', at })
        touch(id)
      })
    },

    /** Brings back a deleted task, for undo. */
    restore(id: string): Task {
      return mutate((touch, at) => {
        const task = repo.findIncludingDeleted(id)
        if (!task) throw new AppError('NOT_FOUND', 'That task no longer exists.')
        if (!task.deleted_at) return toTask(task)

        const overdue = task.status !== 'done' && task.date !== null && task.date < today()
        repo.patch(id, {
          deleted_at: null,
          status: overdue ? 'missed' : task.status,
          missed_at: overdue ? (task.missed_at ?? at) : task.missed_at,
          updated_at: at
        })
        activity.add({ taskId: id, taskTitle: task.title, action: 'restored', at })
        touch(id)
        return toTask(requireTask(id))
      })
    }
  }
}

export type TaskService = ReturnType<typeof createTaskService>
